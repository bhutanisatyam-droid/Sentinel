@router.post("/str")
async def generate_str_report(
    req: STRRequest,
    current_user: Dict[str, str] = Depends(require_role("officer", "admin")),
):
    """Generate a Suspicious Transaction Report (STR) from an alert."""
    from app.engine.alert_templates import generate_str_narrative

    alert_res = supabase.table("alerts").select("*").eq("id", req.alert_id).single().execute()
    if not alert_res.data:
        raise HTTPException(status_code=404, detail="Alert not found")
    alert = alert_res.data

    if alert["status"] == "FILED_STR":
        raise HTTPException(status_code=400, detail="STR already filed for this alert")

    evidence = alert.get("evidence", {})
    sus_txs = evidence.get("suspicious_transactions", [])

    if not sus_txs:
        start_date, end_date, count, total_amount = "UNKNOWN", "UNKNOWN", 0, 0.0
        account_id = alert.get("user_id", "UNKNOWN")
    else:
        sorted_txs = sorted(sus_txs, key=lambda x: x["timestamp"])
        start_date, end_date = sorted_txs[0]["timestamp"], sorted_txs[-1]["timestamp"]
        count = len(sus_txs)
        total_amount = sum(t["amount"] for t in sus_txs)
        account_id = alert.get("user_id")

    narrative_data = {
        "start_date": start_date, "end_date": end_date,
        "account_id": account_id, "count": count, "total_amount": total_amount,
        "primary_rule": alert.get("rule_name", "UNKNOWN"),
        "rule_id": alert.get("rule_id", "UNKNOWN"),
        "threshold": evidence.get("threshold_used", 1000000),
        "officer_name": current_user.get("email", "Unknown Officer"),
        "officer_id": current_user["user_id"],
        "review_date": datetime.utcnow().strftime("%Y-%m-%d"),
    }
    narrative_data.update(evidence)
    report_text = generate_str_narrative(narrative_data)

    report_id = _next_report_id("STR")
    report_entry = {
        "report_id": report_id,
        "alert_id": req.alert_id,
        "type": "STR",
        "generated_by": current_user["user_id"],
        "filed_by": current_user.get("email", "Unknown"),
        "content": report_text,
        "status": "DRAFT",
        "subject": f"STR from Alert {req.alert_id}",
        "user_name": account_id or "Unknown",
        "amount": total_amount,
        "created_at": datetime.utcnow().isoformat(),
    }

    try:
        rep_res = supabase.table("reports").insert(report_entry).execute()
    except Exception as e:
        print(f"Failed to save report: {e}")
        rep_res = type("obj", (object,), {"data": [report_entry]})

    supabase.table("alerts").update({"status": "FILED_STR"}).eq("id", req.alert_id).execute()

    try:
        supabase.table("compliance_audit_logs").insert({
            "user_id": alert.get("user_id", "UNKNOWN"),
            "action": "STR_FILED",
            "performed_by": current_user["user_id"],
            "evidence": {"report_content_snippet": report_text[:200]},
            "timestamp": datetime.utcnow().isoformat(),
            "previous_hash": "STR_EVENT",
            "record_hash": "STR_EVENT",
        }).execute()
    except Exception:
        pass

    return rep_res.data[0]


@router.post("/ctr")
async def generate_ctr_report(
    req: CTRRequest,
    current_user: Dict[str, str] = Depends(require_role("officer", "admin")),
):
    """Generate a Cash Transaction Report (CTR) using a deterministic template."""
    from app.engine.alert_templates import generate_ctr_narrative

    try:
        tx_res = (
            supabase.table("transactions")
            .select("*")
            .eq("user_id", req.account_id)
            .gte("created_at", req.start_date)
            .lte("created_at", req.end_date)
            .limit(1000)
            .execute()
        )
        transactions = tx_res.data or []
    except Exception:
        transactions = []

    count = len(transactions)
    total = sum(t.get("amount", 0) for t in transactions)

    narrative_data = {
        "account_id": req.account_id,
        "total": total,
        "start_date": req.start_date,
        "end_date": req.end_date,
        "count": count,
        "officer_name": current_user.get("email", "Unknown Officer"),
        "officer_id": current_user["user_id"],
        "review_date": datetime.utcnow().strftime("%Y-%m-%d"),
    }
    report_text = generate_ctr_narrative(narrative_data)

    report_id = _next_report_id("CTR")
    report_entry = {
        "report_id": report_id,
        "type": "CTR",
        "filed_by": current_user.get("email", "Unknown"),
        "content": report_text,
        "status": "DRAFT",
        "subject": f"CTR for account {req.account_id}",
        "user_name": req.account_id,
        "amount": total,
        "created_at": datetime.utcnow().isoformat(),
    }

    try:
        rep_res = supabase.table("reports").insert(report_entry).execute()
    except Exception:
        rep_res = type("obj", (object,), {"data": [report_entry]})

    try:
        supabase.table("compliance_audit_logs").insert({
            "user_id": req.account_id,
            "action": "CTR_FILED",
            "performed_by": current_user["user_id"],
            "evidence": {"total": total, "count": count},
            "timestamp": datetime.utcnow().isoformat(),
            "previous_hash": "CTR_EVENT",
            "record_hash": "CTR_EVENT",
        }).execute()
    except Exception:
        pass

    return rep_res.data[0]
