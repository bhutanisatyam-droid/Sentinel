router = APIRouter(prefix="/api/reports", tags=["Reports"])


# ─── Request / Response Models ──────────────────────────────────────

class CreateReportRequest(BaseModel):
    type: str  # STR | CTR | INTERNAL
    subject: str
    user_name: str = ""
    user_id: Optional[str] = None
    amount: float = 0
    filed_by: str = "System"
    content: Optional[str] = None
    alert_id: Optional[str] = None


class UpdateStatusRequest(BaseModel):
    status: str  # DRAFT | PENDING_REVIEW | FILED | REJECTED


class STRRequest(BaseModel):
    alert_id: str


class CTRRequest(BaseModel):
    account_id: str
    start_date: str
    end_date: str


# ─── Helper: generate next report_id ────────────────────────────────

def _next_report_id(report_type: str) -> str:
    """Generate the next sequential report_id like STR-2026-0042."""
    prefix_map = {"STR": "STR", "CTR": "CTR", "INTERNAL": "INT"}
    prefix = prefix_map.get(report_type, "RPT")
    year = datetime.utcnow().strftime("%Y")

    try:
        res = (
            supabase.table("reports")
            .select("report_id")
            .like("report_id", f"{prefix}-{year}-%")
            .execute()
        )
        if res.data:
            max_num = 0
            for row in res.data:
                try:
                    num = int(row["report_id"].split("-")[-1])
                    if num > max_num:
                        max_num = num
                except (ValueError, IndexError):
                    pass
            return f"{prefix}-{year}-{str(max_num + 1).zfill(4)}"
    except Exception:
        pass

    return f"{prefix}-{year}-0001"


# ─── Helper: generate deterministic content ─────────────────────────

def _generate_content(report_type: str, subject: str, user_name: str, amount: float, filed_by: str, report_id: str) -> str:
    """Generate deterministic report content from a template."""
    now = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S")
    amt_str = f"₹{amount:,.0f}"

    if report_type == "STR":
        return (
            f"SUSPICIOUS TRANSACTION REPORT\n"
            f"Filed under: Prevention of Money Laundering Act 2002\n\n"
            f"Report ID: {report_id}\n"
            f"Subject Account: {user_name}\n"
            f"Filed By: {filed_by}\n"
            f"Date Created: {now}\n"
            f"Status: DRAFT\n\n"
            f"NARRATIVE:\n{subject}. Total amount involved: {amt_str}.\n"
            f"Supporting transaction evidence is attached as Annexure A.\n"
            f"This report was generated by the Sentinel compliance platform\n"
            f"and prepared by {filed_by} on {now}.\n\n"
            f"[DETERMINISTIC — No AI-generated text in this filing]"
        )
    elif report_type == "CTR":
        return (
            f"CASH TRANSACTION REPORT\n"
            f"Mandatory filing under PMLA 2002, Rule 3\n\n"
            f"Report ID: {report_id}\n"
            f"Account: {user_name}\n"
            f"Total Cash Transactions: {amt_str}\n"
            f"Threshold: ₹10,00,000\n\n"
            f"This CTR was auto-generated by the Sentinel compliance platform.\n"
            f"Mandatory reporting — no officer discretion required."
        )
    else:
        return (
            f"INTERNAL INVESTIGATION REPORT\n"
            f"Report ID: {report_id}\n"
            f"Subject: {user_name}\n"
            f"Investigator: {filed_by}\n"
            f"Created: {now}\n\n"
            f"Summary: {subject}\n"
            f"Amount under review: {amt_str}\n\n"
            f"[INTERNAL USE ONLY — NOT FOR REGULATORY FILING]"
        )


# ═══════════════════════════════════════════════════════════════════════
#  GET /api/reports — List all reports
# ═══════════════════════════════════════════════════════════════════════

@router.get("")
async def list_reports(
    type: Optional[str] = Query(None, description="Filter by type: STR, CTR, INTERNAL"),
    report_status: Optional[str] = Query(None, alias="status", description="Filter by status"),
    search: Optional[str] = Query(None, description="Search in report_id, subject, user_name"),
    limit: int = Query(100, le=500),
    current_user: Dict[str, str] = Depends(get_optional_user),
):
    """List all reports with optional filtering."""
    try:
        query = supabase.table("reports").select("*").order("created_at", desc=True).limit(limit)

        if type:
            query = query.eq("type", type.upper())
        if report_status:
            query = query.eq("status", report_status.upper())

        res = query.execute()
        reports = res.data or []

        # Client-side search filter (Supabase free tier doesn't support full-text easily)
        if search:
            q = search.lower()
            reports = [
                r for r in reports
                if q in (r.get("report_id", "")).lower()
                or q in (r.get("subject", "")).lower()
                or q in (r.get("user_name", "")).lower()
            ]

        # Compute stats
        all_reports = supabase.table("reports").select("type, status").execute().data or []
        str_filed = sum(1 for r in all_reports if r["type"] == "STR" and r["status"] == "FILED")
        ctr_filed = sum(1 for r in all_reports if r["type"] == "CTR" and r["status"] == "FILED")
        pending = sum(1 for r in all_reports if r["status"] in ("PENDING_REVIEW", "DRAFT"))

        return {
            "reports": reports,
            "stats": {
                "str_filed": str_filed,
                "ctr_filed": ctr_filed,
                "pending": pending,
                "total": len(all_reports),
            },
        }

    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to fetch reports: {str(e)}")


# ═══════════════════════════════════════════════════════════════════════
#  POST /api/reports/create — Create a new report
# ═══════════════════════════════════════════════════════════════════════

@router.post("/create")
async def create_report(
    req: CreateReportRequest,
    current_user: Dict[str, str] = Depends(get_optional_user),
):
    """Create a new STR/CTR/INTERNAL report."""
    if req.type not in ("STR", "CTR", "INTERNAL"):
        raise HTTPException(status_code=400, detail="type must be STR, CTR, or INTERNAL")

    report_id = _next_report_id(req.type)
    content = req.content or _generate_content(
        req.type, req.subject, req.user_name, req.amount, req.filed_by, report_id
    )

    entry = {
        "report_id": report_id,
        "type": req.type,
        "status": "DRAFT",
        "subject": req.subject,
        "user_name": req.user_name,
        "user_id": req.user_id,
        "amount": req.amount,
        "filed_by": req.filed_by,
        "content": content,
        "alert_id": req.alert_id,
        "created_at": datetime.utcnow().isoformat(),
    }

    try:
        res = supabase.table("reports").insert(entry).execute()
        return res.data[0] if res.data else entry
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to create report: {str(e)}")


# ═══════════════════════════════════════════════════════════════════════
#  PATCH /api/reports/{report_id}/status — Update report status
# ═══════════════════════════════════════════════════════════════════════

@router.patch("/{report_id}/status")
async def update_report_status(
    report_id: str,
    req: UpdateStatusRequest,
    current_user: Dict[str, str] = Depends(get_optional_user),
):
    """Update a report's status (e.g., DRAFT → PENDING_REVIEW → FILED)."""
    if req.status not in ("DRAFT", "PENDING_REVIEW", "FILED", "REJECTED"):
        raise HTTPException(status_code=400, detail="Invalid status")

    update_data = {"status": req.status}
    if req.status == "FILED":
        update_data["filed_at"] = datetime.utcnow().isoformat()

    try:
        res = (
            supabase.table("reports")
            .update(update_data)
            .eq("report_id", report_id)
            .execute()
        )
        if not res.data:
            raise HTTPException(status_code=404, detail="Report not found")
        return res.data[0]
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to update report: {str(e)}")


